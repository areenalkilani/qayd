const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({ call, register, makeEmail, admin, password, db }) => {
  const name = `Browser ${makeEmail('management')}`;
  const registration = await call('/auth/register', { ...register(makeEmail('managed-office')), officeName: name });
  assert.equal(registration.status, 201);
  const { chromium } = require('playwright-core');
  const browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(process.env.APP_ORIGIN);
    await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).first().click();
    let dialog = page.getByRole('dialog');
    await dialog.locator('[name=email]').fill(admin.email); await dialog.locator('[name=password]').fill(password);
    await dialog.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await page.locator('.sidebar > nav button').count(), 4);
    await page.locator('.sidebar').getByRole('button', { name: 'طلبات التجربة', exact: true }).click();
    await page.getByLabel('بحث في الحسابات والدفعات').fill(name);
    await page.getByRole('button', { name: 'قبول التجربة', exact: true }).click();
    await page.getByRole('button', { name: 'قبول وبدء تجربة 7 أيام', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByText('لا توجد سجلات مطابقة.', { exact: true }).waitFor();
    await page.locator('.sidebar').getByRole('button', { name: 'حسابات المشتركين', exact: true }).click();
    await page.getByLabel('بحث في الحسابات والدفعات').fill(name);
    await page.getByRole('button', { name: 'تمديد التجربة', exact: true }).click();
    await dialog.getByLabel('عدد الأيام الإضافية').fill('5'); await dialog.getByLabel('سبب التمديد').fill('Browser extension');
    await dialog.getByRole('button', { name: 'تأكيد تمديد التجربة' }).click(); await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'تثبيت الاشتراك', exact: true }).click();
    await dialog.getByLabel('المبلغ المدفوع').fill('250.50');
    await dialog.getByLabel('طريقة الدفع').selectOption('VISA');
    await dialog.getByLabel('مرجع عملية الفيزا').fill('browser-visa');
    await dialog.getByLabel('آخر أربعة أرقام من البطاقة').fill('4242');
    await dialog.getByRole('button', { name: 'تأكيد الدفعة وتثبيت الاشتراك السنوي' }).click(); await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'إيقاف الاشتراك', exact: true }).click();
    await dialog.getByLabel('السبب', { exact: true }).fill('Browser pause');
    await dialog.getByRole('button', { name: 'تأكيد الإيقاف دون حذف البيانات' }).click(); await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'إعادة التفعيل', exact: true }).waitFor();
    const office = await db.office.findFirstOrThrow({ where: { name } }); assert.equal(office.status, 'SUSPENDED');
    await page.screenshot({ path: path.resolve(__dirname, '../../.local-test/screenshots/platform-subscribers.png'), fullPage: true });
    await page.locator('.sidebar').getByRole('button', { name: 'الدفعات', exact: true }).click();
    await page.getByLabel('بحث في الحسابات والدفعات').fill(name);
    await page.getByRole('cell', { name: '250.50 ILS', exact: true }).waitFor();
    await page.locator('.sidebar').getByRole('button', { name: 'الإعدادات', exact: true }).click();
    await page.getByLabel('البريد الإلكتروني للتواصل').waitFor();
    assert.equal(await page.locator('input[name=fullName]').count(), 0);
    await page.getByRole('button', { name: 'تغيير كلمة المرور وإنهاء الجلسات' }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.live-mobile-nav select').selectOption('offices');
    await page.getByLabel('بحث في الحسابات والدفعات').fill(name);
    await page.getByRole('button', { name: 'حذف الحساب', exact: true }).click();
    await dialog.getByRole('button', { name: 'فهمت، انتقل لتأكيد الحذف' }).click();
    await dialog.locator('[name=officeName]').fill(name);
    await dialog.locator('[name=confirmation]').fill('DELETE');
    await dialog.locator('[name=password]').fill(password);
    await dialog.locator('[name=acknowledge]').check();
    await dialog.getByRole('button', { name: 'حذف الحساب وكل بياناته نهائيًا' }).click(); await dialog.waitFor({ state: 'hidden' });
    await page.getByText('لا توجد سجلات مطابقة.', { exact: true }).waitFor();
    assert.equal(await db.office.count({ where: { id: office.id } }), 0);
    assert.deepEqual(errors, []);
  } catch (e) { await page.screenshot({ path: path.resolve(__dirname, '../../.local-test/screenshots/platform-failure.png'), fullPage: true }).catch(() => {}); throw e; }
  finally { await browser.close(); }
};

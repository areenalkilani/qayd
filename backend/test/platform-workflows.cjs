const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
module.exports = async (t, { call, db, adminCookie, cookieA, a, password, makeEmail, register, login }) => {
  const email = makeEmail('platform-victim');
  const name = `Management ${randomUUID()}`;
  assert.equal((await call('/auth/register', { ...register(email), officeName: name })).status, 201);
  const owner = await db.user.findUniqueOrThrow({ where: { email } });
  const id = owner.officeId;
  const cookie = await login(email);
  const endpoint = `/platform/offices/${id}`;
  const payment = { reference: 'cash-reference', amount: '123.45', currency: 'ILS', method: 'CASH', cardLast4: '', paidAt: new Date().toISOString() };
  let fileKey;
  await t.test('trial extension and suspension preserve office data and separate trial/subscriber lists', async () => {
    assert.equal((await call(`${endpoint}/extend-trial`, { days: 7, reason: 'test' }, cookieA)).status, 403);
    assert.equal((await call(`${endpoint}/review`, { decision: 'APPROVE', note: '' }, adminCookie)).status, 201);
    const old = await db.trial.findUniqueOrThrow({ where: { officeId: id } });
    assert.equal((await call(`${endpoint}/extend-trial`, { days: 3, reason: 'requested extension' }, adminCookie)).status, 201);
    const extended = await db.trial.findUniqueOrThrow({ where: { officeId: id } });
    assert.equal(extended.expiresAt - old.expiresAt, 3 * 86400000);
    const client = await db.client.create({ data: { officeId: id, name: 'Keep client', phone: '+1234567890' } });
    const court = await db.court.create({ data: { officeId: id, name: 'Keep court', normalizedName: 'keep court' } });
    const legal = await db.legalCase.create({ data: { officeId: id, clientId: client.id, courtId: court.id, creatorId: owner.id, lawyerId: owner.id, internalNumber: 'KEEP-001', courtNumber: 'KEEP', type: 'test', receivedAt: new Date() } });
    const hearing = await db.hearing.create({ data: { officeId: id, caseId: legal.id, courtId: court.id, lawyerId: owner.id } });
    await db.hearingReschedule.create({ data: { officeId: id, hearingId: hearing.id, reason: 'keep', actorId: owner.id } });
    await db.assignmentHistory.create({ data: { officeId: id, caseId: legal.id, actorId: owner.id, reason: 'keep' } });
    await db.legalProcedure.create({ data: { officeId: id, caseId: legal.id, assignedId: owner.id, title: 'keep', dueAt: new Date() } });
    fileKey = `${randomUUID()}.pdf`;
    await fs.mkdir(process.env.STORAGE_ROOT, { recursive: true }); await fs.writeFile(path.join(process.env.STORAGE_ROOT, fileKey), 'test');
    await db.caseAttachment.create({ data: { officeId: id, caseId: legal.id, originalName: 'test.pdf', storageKey: fileKey, contentType: 'application/pdf', size: 4, sha256: 'test', uploadedBy: owner.id } });
    assert.equal((await call(`${endpoint}/status`, { suspended: true, reason: 'pause test' }, adminCookie)).status, 201);
    assert.equal((await call('/legal/cases', undefined, cookie)).status, 403);
    assert.equal(await db.legalCase.count({ where: { officeId: id } }), 1);
    assert.equal((await call(`${endpoint}/extend-trial`, { days: 2, reason: 'paused extension' }, adminCookie)).status, 201);
    assert.equal((await db.office.findUniqueOrThrow({ where: { id } })).status, 'SUSPENDED');
    const trials = await call(`/platform/offices?group=TRIALS&search=${encodeURIComponent(name)}`, undefined, adminCookie);
    assert.equal(trials.body.items.length, 0);
    assert.equal((await call(`/platform/offices?group=SUBSCRIBERS&search=${encodeURIComponent(name)}`, undefined, adminCookie)).body.total, 1);
  });
  await t.test('subscription payment is atomic, exact, idempotent and moves account to subscribers', async () => {
    assert.equal((await call(`${endpoint}/subscriptions`, { reference: 'missing-payment' }, adminCookie)).status, 400);
    const concurrent = await Promise.all([1, 2].map(() => call(`${endpoint}/subscriptions`, payment, adminCookie)));
    assert.deepEqual(concurrent.map(r => r.status).sort(), [201, 409]);
    assert.equal(await db.subscription.count({ where: { officeId: id } }), 1);
    const rows = await db.$queryRaw`SELECT amount::text AS amount FROM "PlatformPayment" WHERE "officeId" = ${id}::uuid`;
    assert.equal(rows[0].amount, '123.45');
    assert.equal((await call('/legal/cases', undefined, cookie)).status, 200);
    assert.equal((await call(`/platform/offices?group=TRIALS&search=${encodeURIComponent(name)}`, undefined, adminCookie)).body.total, 0);
    assert.equal((await call(`/platform/offices?group=SUBSCRIBERS&search=${encodeURIComponent(name)}`, undefined, adminCookie)).body.total, 1);
    assert.equal((await call(`${endpoint}/extend-trial`, { days: 7, reason: 'invalid extension' }, adminCookie)).status, 409);
    assert.equal((await call(`${endpoint}/subscriptions`, { ...payment, reference: 'visa', method: 'VISA', cardLast4: '1234567812345678' }, adminCookie)).status, 400);
    assert.equal((await call(`${endpoint}/subscriptions`, { ...payment, reference: 'visa', method: 'VISA', cardLast4: '1234', cvv: '123' }, adminCookie)).status, 400);
    assert.equal((await call(`${endpoint}/subscriptions`, { ...payment, reference: 'visa', method: 'VISA', cardLast4: '1234' }, adminCookie)).status, 201);
    const subs = await db.subscription.findMany({ where: { officeId: id }, orderBy: { startsAt: 'asc' } });
    assert.equal(subs[0].expiresAt.getTime(), subs[1].startsAt.getTime());
    assert.equal((await call('/platform/payments', undefined, cookie)).status, 403);
    assert.equal((await call(`/platform/payments?search=${encodeURIComponent(name)}`, undefined, adminCookie)).body.total, 2);
    assert.equal(await db.legalCase.count({ where: { officeId: id } }), 1);
  });
  await t.test('full deletion requires admin password and explicit confirmations, removes files and leaves other tenants intact', async () => {
    const input = { password, officeName: name, confirmation: 'DELETE', acknowledge: true };
    assert.equal((await call(`${endpoint}/delete`, input, cookieA)).status, 403);
    assert.equal((await call(`${endpoint}/delete`, { ...input, password: 'incorrect' }, adminCookie)).status, 401);
    assert.equal((await call(`${endpoint}/delete`, { ...input, officeName: 'wrong office' }, adminCookie)).status, 400);
    assert.equal((await call(`${endpoint}/delete`, { ...input, acknowledge: false }, adminCookie)).status, 400);
    assert.equal(await db.legalCase.count({ where: { officeId: id } }), 1);
    const result = await call(`${endpoint}/delete`, input, adminCookie);
    assert.equal(result.status, 201, JSON.stringify(result.body));
    assert.equal(await db.office.count({ where: { id } }), 0);
    assert.equal(await db.user.count({ where: { officeId: id } }), 0);
    assert.equal(await db.legalCase.count({ where: { officeId: id } }), 0);
    assert.equal(await db.audit.count({ where: { officeId: id } }), 0);
    assert.equal((await call('/auth/me', undefined, cookie)).status, 401);
    await assert.rejects(fs.stat(path.join(process.env.STORAGE_ROOT, fileKey)), { code: 'ENOENT' });
    assert.equal(await db.office.count({ where: { id: a.officeId } }), 1);
    assert.ok(await db.audit.count({ where: { targetId: id, action: 'OFFICE_DELETED', officeId: null } }));
  });
};
